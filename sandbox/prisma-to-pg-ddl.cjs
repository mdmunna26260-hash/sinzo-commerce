#!/usr/bin/env node
/* Prisma schema (postgres provider) → CREATE TABLE DDL script.
   Sandbox helper: parses model blocks (no enums/@db types in this schema)
   and emits DDL for a fresh local PG database. */
const fs = require("fs");

const file = process.argv[2];
const src = fs.readFileSync(file, "utf8");

// strip comments
let s = src.replace(/\/\/[^\n]*/g, "").replace(/\/\*[\s\S]*?\*\//g, "");

const TYPE_MAP = {
  Int: "INTEGER", BigInt: "BIGINT", String: "TEXT", Boolean: "BOOLEAN",
  DateTime: "TIMESTAMP(3)", Decimal: "DECIMAL(65,30)", Json: "JSONB",
  Bytes: "BYTEA", Float: "DOUBLE PRECISION",
};

function parseDefault(d) {
  if (d.startsWith("autoincrement")) return "IDENTITY";
  if (d.startsWith("now")) return "CURRENT_TIMESTAMP";
  if (d.startsWith("uuid")) return "gen_random_uuid()";
  if (d.startsWith("cuid")) return "gen_random_uuid()::text";
  if (d.startsWith("dbgenerated")) return null; // let DB handle
  if (d === "true" || d === "false") return d.toUpperCase();
  if (/^-?\d+(\.\d+)?$/.test(d)) return d;
  if (d.startsWith('"')) return "'" + d.slice(1, -1).replace(/'/g, "''") + "'";
  if (d.startsWith("'")) return d.replace(/''/g, "''''");
  return d; // function call etc.
}

// extract blocks
const blocks = [];
const re = /(model|enum)\s+(\w+)\s*\{/g;
let m;
while ((m = re.exec(s))) {
  let depth = 1, i = re.lastIndex;
  while (depth > 0 && i < s.length) {
    if (s[i] === "{") depth++;
    else if (s[i] === "}") depth--;
    i++;
  }
  blocks.push({ kind: m[1], name: m[2], body: s.slice(re.lastIndex, i - 1) });
}

const out = [];
out.push("BEGIN;");
for (const b of blocks) {
  if (b.kind !== "model") continue; // no enums in this schema
  const cols = [];
  const constraints = [];
  const indexes = [];
  for (let rawLine of b.body.split("\n")) {
    const line = rawLine.trim();
    if (!line) continue;
    if (line.startsWith("@@")) {
      const mm = /^@@(unique|index)\(\[([^\]]*)\](?:,\s*name:\s*"([^"]+)")?\)/.exec(line);
      if (mm) {
        const fields = mm[2].split(",").map((x) => `"${x.trim()}"`).join(", ");
        if (mm[1] === "unique") constraints.push(`CONSTRAINT "${(mm[3] || b.name + "_" + mm[2].replace(/[^\w]/g, "_") + "_key").slice(0, 60)}" UNIQUE (${fields})`);
        else indexes.push({ name: (mm[3] || "idx_" + b.name + "_" + mm[2].replace(/[^\w]/g, "_")).slice(0, 60), fields });
      }
      continue;
    }
    const fm = /^(\w+)\s+([\w\[\]]+)(\?)?\s*(.*)$/.exec(line);
    if (!fm) continue;
    const [, fname, ftype, opt, attrs] = fm;
    if (attrs.includes("@relation") && !TYPE_MAP[ftype]) continue; // object relation field — not a column
    if (attrs.includes("@ignore")) continue;
    const base = TYPE_MAP[ftype];
    if (!base) continue;
    let col = `"${fname}" ${base}`;
    const idm = /@id\b/.exec(attrs);
    const defm = /@default\((.*)\)\s*$/.exec(attrs);
    if (idm && defm && defm[1].startsWith("autoincrement")) {
      col = `"${fname}" ${ftype === "BigInt" ? "BIGINT" : "INTEGER"} GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
    } else {
      if (idm) col += " PRIMARY KEY";
      if (defm) {
        const d = parseDefault(defm[1]);
        if (d === "IDENTITY") { /* handled */ }
        else if (d) col += ` DEFAULT ${d}`;
      }
      if (!opt && !idm && !defm) col += " NOT NULL";
    }
    if (/@unique\b/.test(attrs)) col += " UNIQUE";
    cols.push(col);
  }
  if (cols.length) {
    out.push(`CREATE TABLE IF NOT EXISTS "${b.name}" (\n  ${[...cols, ...constraints].join(",\n  ")}\n);`);
    for (const ix of indexes) out.push(`CREATE INDEX IF NOT EXISTS "${ix.name}" ON "${b.name}" (${ix.fields});`);
  }
}
out.push("COMMIT;");
console.log(out.join("\n"));
