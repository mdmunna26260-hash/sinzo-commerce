/* Keep prisma/schema.prod.prisma identical to prisma/schema.prisma except for the datasource.
 *
 * Why this exists: the two files describe the same database and only the provider differs
 * (SQLite in dev, PostgreSQL in production). They were maintained by hand and did drift — the
 * dev copy was once missing preorder/preorderDate/soldMode, which crashed every page that
 * selected those columns. Generating one from the other makes that class of bug impossible.
 *
 *   npm run schema:sync      # after editing prisma/schema.prisma
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const devPath = path.join(root, "prisma", "schema.prisma");
const prodPath = path.join(root, "prisma", "schema.prod.prisma");

const HEADER = `// PRODUCTION schema (PostgreSQL) — used by Vercel builds + prod db push.
// Local dev keeps using prisma/schema.prisma (SQLite).
// GENERATED by scripts/sync-prod-schema.js — edit prisma/schema.prisma instead, then run
//   npm run schema:sync
// Usage:
//   npx prisma db push --schema prisma/schema.prod.prisma
//   npx prisma generate --schema prisma/schema.prod.prisma
// Requires DATABASE_URL (PostgreSQL connection string) in the environment.
`;

const dev = fs.readFileSync(devPath, "utf8");
// drop the dev file's own header comment block (everything before the generator)
const body = dev.slice(dev.indexOf("generator client {"));
const prod = HEADER + "\n" + body.replace('provider = "sqlite"', 'provider = "postgresql"');

const current = fs.existsSync(prodPath) ? fs.readFileSync(prodPath, "utf8") : "";
if (current === prod) {
  console.log("[schema:sync] prisma/schema.prod.prisma is already in sync.");
} else {
  fs.writeFileSync(prodPath, prod);
  console.log("[schema:sync] wrote prisma/schema.prod.prisma from prisma/schema.prisma (provider → postgresql).");
}
